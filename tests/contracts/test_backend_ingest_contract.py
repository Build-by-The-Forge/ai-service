@pytest.mark.asyncio
async def test_backend_4b4_dispatch_contract_accepted():
    """
    Contract Test: Asserts that the exact request emitted by BUILD Backend 4B.4
    is valid, parsed into IngestDispatchRequest, accepted by the AI Service,
    and returns a valid IngestDispatchResponse.
    """
    backend_payload = {
        "job_id": "job_01j9a8b7c6d5e4f3a2b1c0d9e8",
        "asset_id": "asset_01j9a8b7c6d5e4f3a2b1c0d9e9",
        "tenant_id": "school_futa_01",
        "source": "upload",
        "authority": "INSTITUTIONAL",
        "storage_uri": "s3://build-assets-prod/futa/cos102/2026/course_pack.pdf",
        "mime_type": "application/pdf",
        "content_sha256": "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789",
        "run_number": 1,
        "attempt_count": 1,
        "correlation_id": "corr_01j9a8b7c6d5e4f3a2b1c0d9ea",
        "idempotency_key": "idemp_backend_contract_001",
        "callback_url": "https://api.build.internal/v1/content-ingestion/jobs/job_01j9a8b7c6d5e4f3a2b1c0d9e8/callback",
        "metadata": {
            "course_code": "COS 102",
            "course_title": "Introduction to Computer Science",
            "department": "Computer Science",
            "semester": "Harmattan",
            "level": "100L",
        },
    }

    # Validate against Pydantic schema
    parsed_req = IngestDispatchRequest(**backend_payload)
    assert parsed_req.authority == ContentAuthority.INSTITUTIONAL
    assert parsed_req.run_number == 1

    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://testserver") as client:
        body_bytes = json.dumps(backend_payload).encode("utf-8")
        timestamp = int(time.time())
        signature = compute_service_signature(
            method="POST",
            path="/v1/ingest/dispatch",
            timestamp=timestamp,
            body=body_bytes,
            secret=settings.BACKEND_TO_AI_SECRET,
        )

        response = await client.post(
            "/v1/ingest/dispatch",
            content=body_bytes,
            headers={
                "X-Service-Identity": "build-backend",
                "X-Timestamp": str(timestamp),
                "X-Service-Signature": signature,
                "Content-Type": "application/json",
            },
        )

        assert response.status_code == 202
        data = response.json()

        # Validate response schema
        dispatch_response = IngestDispatchResponse(**data)
        assert dispatch_response.success is True
        assert dispatch_response.status == DispatchStatus.ACCEPTED
        assert dispatch_response.external_task_id.startswith("task_")


@pytest.mark.asyncio
async def test_backend_4b4_callback_schema_contract():
    """
    Contract Test: Asserts that callback payloads generated by the AI Service
    satisfy the Backend 4B.4 callback schema specifications.
    """
    sample_progress_event = {
        "job_id": "job_01j9a8b7c6d5e4f3a2b1c0d9e8",
        "asset_id": "asset_01j9a8b7c6d5e4f3a2b1c0d9e9",
        "tenant_id": "school_futa_01",
        "run_number": 1,
        "attempt_count": 1,
        "external_task_id": "task_1234567890abcdef",
        "correlation_id": "corr_01j9a8b7c6d5e4f3a2b1c0d9ea",
        "event_type": "PROGRESS",
        "progress_pct": 45,
        "extracted_metadata": {"pages_processed": 37, "total_pages": 82},
    }

    callback_payload = IngestCallbackPayload(**sample_progress_event)
    assert callback_payload.event_type == CallbackEventType.PROGRESS
    assert callback_payload.progress_pct == 45
    assert callback_payload.extracted_metadata["pages_processed"] == 37

    sample_failed_event = {
        "job_id": "job_01j9a8b7c6d5e4f3a2b1c0d9e8",
        "asset_id": "asset_01j9a8b7c6d5e4f3a2b1c0d9e9",
        "tenant_id": "school_futa_01",
        "run_number": 1,
        "attempt_count": 1,
        "external_task_id": "task_1234567890abcdef",
        "correlation_id": "corr_01j9a8b7c6d5e4f3a2b1c0d9ea",
        "event_type": "FAILED",
        "error_code": "OCR_EXTRACTION_TIMEOUT",
        "error_message": "PaddleOCR processing exceeded 120s timeout limit",
        "retryable": True,
    }

    failed_callback = IngestCallbackPayload(**sample_failed_event)
    assert failed_callback.event_type == CallbackEventType.FAILED
    assert failed_callback.retryable is True
